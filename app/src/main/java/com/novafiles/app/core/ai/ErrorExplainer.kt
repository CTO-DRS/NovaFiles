    /** شرح نص خطأ خام — أول توقيع مطابق، وإلا توقيع عام */
    fun explain(raw: String): Explanation {
        val t = ArabicText.normalize(raw)
        for (r in rules) {
            if (r.keywords.any { t.contains(ArabicText.normalize(it)) }) {
                return Explanation(r.signature, r.titleAr, r.hintsAr)
            }
        }
        return Explanation(
            "unknown",
            "لم أتعرف على توقيع هذا الخطأ تحديداً",
            listOf(
                "انسخ نص الخطأ كاملاً إن أردت مراجعته لاحقاً",
                "أعد المحاولة بعد التأكد من الشبكة والصلاحيات والمساحة",
            ),
        )
    }
